'use strict';

const nconf = require('nconf');
const winston = require('winston');

const db = require('../database');
const utils = require('../utils');

const secrets = module.exports;

// How long secondary processes wait for the primary to generate a secret (in a cluster).
const POLL_INTERVAL = 250;
const POLL_RETRIES = 20;

const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));

/**
 * Resolves the secret used to sign session cookies, socket.io cookies, and JWTs, and makes it
 * available to nconf consumers (i.e. `nconf.get('secret')`).
 *
 * Precedence, from highest to lowest:
 *  - command line arguments (`--secret`)
 *  - environment variables (`SECRET`)
 *  - config.json (`secret`)
 *  - the secret saved to the `global` hash in the database
 *  - a newly generated secret
 *
 * A secret configured elsewhere (env, config.json) takes precedence over the saved value, and is
 * saved to the database, so that the database remains the canonical store of the secret.
 *
 * N.B. Security-hardened deployments are encouraged to set the SECRET environment variable instead.
 *
 * @returns {Promise<string>} the resolved secret
 */
secrets.init = async function () {
	// nconf consults the command line, environment, and config.json, in that order
	let secret = nconf.get('secret') || await db.getObjectField('global', 'secret');

	if (!secret && !nconf.get('isPrimary')) {
		secret = await waitForSecret(); // primary process generates secret
	}

	if (!secret) {
		secret = utils.generateUUID();
		winston.info('[secret] No secret found, generated a new one');
	}

	if (await db.getObjectField('global', 'secret') !== secret) {
		await db.setObjectField('global', 'secret', secret);
		winston.verbose('[secret] Saved secret to the database (global hash)');
	}

	// Make the resolved secret available to nconf consumers (cookie parser, session, jwt)
	nconf.set('secret', secret);
	return secret;
};

/**
 * Returns the secret, resolving it (and saving it to the database) if not yet done.
 * @returns {Promise<string>} the secret
 */
secrets.get = async function () {
	return nconf.get('secret') || secrets.init();
};

async function waitForSecret() {
	for (let i = 0; i < POLL_RETRIES; i++) {
		// eslint-disable-next-line no-await-in-loop
		const stored = await db.getObjectField('global', 'secret');
		if (stored) {
			return stored;
		}
		// eslint-disable-next-line no-await-in-loop
		await sleep(POLL_INTERVAL);
	}

	winston.warn('[secret] Secondary process could not find a secret generated by the primary, generating its own');
	return undefined;
}
